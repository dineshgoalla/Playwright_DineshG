// Naming Conventions (Cases)
// ============================================
// 1. camelCase (standard for JS variables and functions)
let userName = "camelCase";
let totalPrice = 99.99;
let isLoggedIn = true;

// 2. PascalCase (standard for JS classes and constructors)
let UserProfile = "PascalCase";
let ShoppingCart = "class name style";

// 3. snake_case (underscore separated)
let user_name = "snake_case";
let total_price = 49.99;
let is_logged_in = false;

// 4. SCREAMING_SNAKE_CASE (constants)
const MAX_SIZE = 100;
// MAX_SIZE  =90;
const API_KEY = "abc123";
const DATABASE_URL = "localhost";

// 5. Hungarian Notation (prefix with type - older style)
let strName = "string prefix";
let bActive = true;       // boolean
let nCount = 5;           // number
let arrItems = [];        // array

/*### Learning Summary – JavaScript Identifier Naming Conventions

1. **Meaningful Names:** Use clear and meaningful names for variables, such as `firstName` and `lastName`.

2. **camelCase:** Start with a lowercase letter and capitalize the first letter of each following word. Commonly used for JavaScript variables and functions. Example: `userName`, `totalPrice`.

3. **PascalCase:** Capitalize the first letter of every word. Commonly used for classes and constructors. Example: `UserProfile`, `ShoppingCart`.

4. **snake_case:** Separate words using underscores. Example: `user_name`, `total_price`.

5. **SCREAMING_SNAKE_CASE:** Use uppercase letters with underscores. Commonly used for constants. Example: `MAX_SIZE`, `API_KEY`.

6. **Hungarian Notation:** Add a prefix to indicate the data type. Example: `strName` (string), `bActive` (boolean), `nCount` (number). This is an older naming style and is not commonly required in modern JavaScript.

**Key Learning:** JavaScript supports different naming conventions, but **camelCase is the standard choice for variables and functions**, PascalCase is common for classes, and SCREAMING_SNAKE_CASE is often used for constants;*/
